const SOL_HASH = `import hashlib

ALGOS = ("md5", "sha1", "sha256", "sha512")


def hash_text(text, algo="sha256"):
    """Вернуть hex-хеш строки text алгоритмом algo."""
    if algo not in ALGOS:
        raise ValueError("Неизвестный алгоритм: " + str(algo))
    h = hashlib.new(algo)
    h.update(text.encode("utf-8"))
    return h.hexdigest()
`;

const SOL_PASSWORD = `import secrets
import string


def generate_password(length=16, use_symbols=True):
    """Случайный пароль: гарантированно есть строчная, заглавная, цифра (и символ)."""
    if length < 8:
        raise ValueError("Пароль короче 8 символов небезопасен")
    pools = [string.ascii_lowercase, string.ascii_uppercase, string.digits]
    if use_symbols:
        pools.append("!@#$%^&*-_?")
    chars = [secrets.choice(p) for p in pools]  # по одному символу из каждой группы
    alphabet = "".join(pools)
    while len(chars) < length:
        chars.append(secrets.choice(alphabet))
    # перемешиваем безопасным генератором
    result = []
    while chars:
        result.append(chars.pop(secrets.randbelow(len(chars))))
    return "".join(result)


def check_password(pw):
    """Вернуть (оценка 0..5, список советов)."""
    score = 0
    tips = []
    if len(pw) >= 12:
        score += 1
    else:
        tips.append("Сделай пароль длиннее 12 символов")
    if any(c.islower() for c in pw):
        score += 1
    else:
        tips.append("Добавь строчные буквы")
    if any(c.isupper() for c in pw):
        score += 1
    else:
        tips.append("Добавь заглавные буквы")
    if any(c.isdigit() for c in pw):
        score += 1
    else:
        tips.append("Добавь цифры")
    if any(not c.isalnum() for c in pw):
        score += 1
    else:
        tips.append("Добавь символы вроде !@#")
    if pw.lower() in ("password", "qwerty", "123456", "12345678", "letmein", "admin"):
        score = 0
        tips.append("Это один из самых популярных паролей мира")
    return score, tips
`;

const SOL_ENCODE = `import base64
import urllib.parse


def encode_text(text, method):
    """method: base64 | hex | url"""
    if method == "base64":
        return base64.b64encode(text.encode("utf-8")).decode("ascii")
    if method == "hex":
        return text.encode("utf-8").hex()
    if method == "url":
        return urllib.parse.quote(text, safe="")
    raise ValueError("Неизвестный метод: " + str(method))


def decode_text(data, method):
    if method == "base64":
        return base64.b64decode(data).decode("utf-8")
    if method == "hex":
        return bytes.fromhex(data).decode("utf-8")
    if method == "url":
        return urllib.parse.unquote(data)
    raise ValueError("Неизвестный метод: " + str(method))
`;

const SOL_CIPHERS = `def caesar(text, shift):
    """Шифр Цезаря для латиницы; регистр сохраняем, остальное не трогаем.
    Для расшифровки передай отрицательный сдвиг."""
    out = []
    for ch in text:
        if "a" <= ch <= "z":
            out.append(chr((ord(ch) - ord("a") + shift) % 26 + ord("a")))
        elif "A" <= ch <= "Z":
            out.append(chr((ord(ch) - ord("A") + shift) % 26 + ord("A")))
        else:
            out.append(ch)
    return "".join(out)


def vigenere(text, key, decrypt=False):
    """Шифр Виженера (латиница). Ключ двигается только на буквах."""
    if not key or not key.isalpha():
        raise ValueError("Ключ должен состоять из букв")
    key = key.lower()
    out = []
    i = 0
    for ch in text:
        if ch.isascii() and ch.isalpha():
            shift = ord(key[i % len(key)]) - ord("a")
            if decrypt:
                shift = -shift
            out.append(caesar(ch, shift))
            i += 1
        else:
            out.append(ch)
    return "".join(out)
`;

const SOL_LOGS = `def analyze_log(lines, threshold=3):
    """Посчитать неудачные входы по IP. Вернуть {ip: число} только для ip с числом >= threshold."""
    counts = {}
    for line in lines:
        if "Failed password" not in line:
            continue
        words = line.split()
        if "from" not in words:
            continue
        ip = words[words.index("from") + 1]
        counts[ip] = counts.get(ip, 0) + 1
    return {ip: n for ip, n in counts.items() if n >= threshold}
`;

const SOL_PORTS = `def is_local(host):
    """Сканер разрешён только для своей машины."""
    return host in ("127.0.0.1", "localhost", "::1")


def parse_ports(spec):
    """'22,80,100-102' -> [22, 80, 100, 101, 102] (по возрастанию, без повторов)."""
    ports = set()
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-")
            a, b = int(a), int(b)
            if a > b:
                raise ValueError("Диапазон задан наоборот: " + part)
            ports.update(range(a, b + 1))
        else:
            ports.add(int(part))
    for p in ports:
        if not 1 <= p <= 65535:
            raise ValueError("Порт вне диапазона 1-65535: " + str(p))
    return sorted(ports)


def scan_port(host, port, timeout=0.5):
    """Проверить один TCP-порт. Только localhost!"""
    import socket

    if not is_local(host):
        raise PermissionError("Сканируем только свою машину (localhost)")
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(timeout)
        return s.connect_ex((host, port)) == 0
`;

